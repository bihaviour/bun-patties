#!/usr/bin/env bun
// Bake the workspace's current `patties` / `patties-ui` versions into
// src/versions.ts so scaffolded apps pin `^<version>` instead of `latest`.
// create-patties stays offline and zero-dependency, so the versions travel
// inside the published source. The root `version` script runs this after
// `changeset version`.
//
//   bun run sync:versions          # rewrite src/versions.ts
//   bun run sync:versions --check  # fail if it is stale

import { dirname, resolve } from "node:path";

const PKG_ROOT = resolve(dirname(import.meta.dir));
const OUT = resolve(PKG_ROOT, "src/versions.ts");

async function versionOf(pkg: string): Promise<string> {
	const json = (await Bun.file(
		resolve(PKG_ROOT, "..", pkg, "package.json"),
	).json()) as { version: string };
	return json.version;
}

const source = `// Generated by scripts/sync-versions.ts — do not edit. Versions of the
// workspace packages this create-patties release ships alongside.
export const PATTIES_VERSION = ${JSON.stringify(await versionOf("patties"))};
export const PATTIES_UI_VERSION = ${JSON.stringify(await versionOf("patties-ui"))};
`;

if (process.argv.includes("--check")) {
	const current = (await Bun.file(OUT).exists())
		? await Bun.file(OUT).text()
		: "";
	if (current !== source) {
		console.error(
			"src/versions.ts is stale — run `bun run --filter create-patties sync:versions`",
		);
		process.exit(1);
	}
} else {
	await Bun.write(OUT, source);
}
